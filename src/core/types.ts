/**
 * 移動速度の変異。指定した種は speed を種の定数ではなく個体ごとの値として持ち、
 * 繁殖のたびに親の値へノイズを乗せて子に渡す。
 *
 * 省略した種は全個体が speed のまま動かず、乱数も一切消費しないので、
 * 既存の構成の結果はこの機構を入れる前と完全に一致する。
 */
export interface MutationDef {
  /** 子に乗るずれの標準偏差（速度の単位）。0 なら親と同じ速度の子が生まれる */
  speedSigma: number;
  /** 速度の下限。0 を許すと動かない個体が生まれる */
  speedMin: number;
  /** 速度の上限 */
  speedMax: number;
}

/**
 * 密度に比例した追加の死亡。負の頻度依存（kill-the-winner）を**手で書いた**もの。
 *
 * 狙いは「増えた側ほど叩かれると共存が生まれるのか」だけを先に確かめること。
 * 本命は接触で伝わる感染で、そちらなら頻度依存は接触の数え方から自然に出るが、
 * 実装した先で効かなかったときに機構の失敗とバグを区別できない。
 * ここで先に答えを持っておくための足場で、**それ自体は機構の主張ではない**。
 *
 * 密度は世界全体の平均（個体数 ÷ セル数）で、局所density ではない。
 * 空間の粗密が混ざると、効いたときに「頻度依存が効いた」のか
 * 「空間構造が効いた」のか分けられなくなるため。空間を入れるのは段2の仕事。
 *
 * 省略すると何も起きず、乱数も一切消費しない。
 */
export interface CrowdingDef {
  /**
   * 密度1個体/セルあたりの、1ステップの追加死亡確率。
   * 既定の環境（10800セル）で個体数1300なら密度0.12なので、
   * rate=0.02 で 1ステップあたり 0.0024 の死亡確率になる。
   */
  rate: number;
  /**
   * 何の密度を数えるか。
   *
   * - `self` — **自種だけ**。増えた種ほど自分で自分の首を絞めるので、
   *   種内の抑制が種間の抑制より強くなる。共存の条件そのもの
   * - `all` — 全種の合計。**対照**。関数形も除去量もほぼ同じまま、
   *   「誰の密度を見るか」だけが違う。ここで差が出なければ、
   *   効いているのは頻度依存ではなく単に数を減らしたこと
   *
   * 15 で測ったとおり、均等に減らすだけでは共存は生まれない。
   * `all` はその結果を同じ関数形で引き直すためにある。
   */
  scope: 'self' | 'all';
}

/**
 * 接触で伝わる感染症。負の頻度依存（kill-the-winner）を**機構として**書いたもの。
 *
 * [16](../../docs/reports/16-crowding.md) の crowding は自種の密度を直接読んで
 * 死亡確率に変えていた。あれは共存条件を式で置いただけで、機構ではない。
 * こちらは**同じセルにいる感染個体の数**しか見ない。それでも増えた種ほど
 * 同型との遭遇が増えるので、頻度依存は接触の数え方から**勝手に出る**。
 * 手で「多いほうを叩く」と書かないのが要点。
 *
 * 省略すると何も起きず、乱数も一切消費しない。
 */
export interface InfectionDef {
  /**
   * 同じセルにいる感染個体1体あたりの、1ステップの伝染確率 (0-1)。
   * k体いれば `1 - (1-transmit)^k` で判定する。
   */
  transmit: number;
  /** 感染個体が1ステップに死ぬ確率 */
  lethality: number;
  /** 感染個体が1ステップに治って未感染に戻る確率。0なら治らない */
  recover: number;
  /**
   * 接触によらず感染する確率（1個体1ステップあたり）。
   *
   * これが無いと、病原体が一度絶えた種は二度と叩かれなくなる。
   * ただし**これ自体は密度に依存しない死**なので、大きくすると
   * [15](../../docs/reports/15-frequency-dependence.md) で潰した「均等な死」に
   * 化ける。接触経由と自然発生の内訳は World が別々に数えているので、
   * どちらが効いているかを必ず確かめること。
   */
  spontaneous: number;
  /** 初期個体のうち感染している割合 */
  initial: number;
  /**
   * 誰から誰へ移るか。
   *
   * - `self` — **同種のみ**（宿主特異的）。増えた種ほど同型との遭遇が増えるので、
   *   自分の密度が自分の死亡率を上げる。これが kill-the-winner の中身
   * - `all` — 種を問わず移る。**対照**。機構も強さのつまみも同じで、
   *   宿主特異性だけが無い。この場合リスクは全体の密度で決まるので、
   *   16 の `scope: 'all'` と同じく「ただの密度依存の死」になるはず
   */
  scope: 'self' | 'all';
}

/**
 * 種の定義。捕食関係を preys で持つので、種を足せば連鎖が伸びる。
 * ここに書いたものが全てで、シミュレーション側に種別のハードコードは無い。
 */
export interface SpeciesDef {
  id: number;
  name: string;
  /** 描画色 "#rrggbb" */
  color: string;

  /** 地面の草を食べるか */
  eatsGrass: boolean;
  /** 捕食する種の id。複数指定可 */
  preys: number[];

  /**
   * 1ステップあたりの基礎エネルギー消費。実際に減る量はこれに行動コストが乗る：
   *
   *   実効代謝 = metabolism + speedCost × speed + visionCost × visionRange
   *
   * 両コストが0なら実効代謝 = metabolism で、行動は無料。
   */
  metabolism: number;
  /** 移動速度1あたりの追加消費。速い個体ほど燃費が悪くなる */
  speedCost: number;
  /** 視野1あたりの追加消費。感覚器の維持費に相当 */
  visionCost: number;
  /** 草を1回食べて得るエネルギー（セルの残量が上限） */
  gainFromGrass: number;
  /** 獲物を1体食べて得るエネルギー */
  gainFromPrey: number;
  /**
   * 同じセルの獲物に襲いかかって成功する確率 (0-1)。狩りは1ステップ1回で、
   * 失敗するとそのステップは何も食べられない。
   *
   * 視界を使う場合はここを1未満にしないと成立しない。追跡が決定的なので、
   * 1.0のままだと「速度が足りず永遠に捕まえられない」か
   * 「必ず捕まえて獲物を絶滅させる」の二択になる。
   */
  captureRate: number;

  /** 繁殖に必要なエネルギー */
  reproduceThreshold: number;
  /** 条件を満たしたステップで実際に繁殖する確率 */
  reproduceProb: number;
  /** 親が子に渡すエネルギーの割合 (0-1) */
  reproduceCost: number;

  /**
   * 1ステップに動けるセル数。0なら動かない。
   *
   * mutation を指定した種では、これは初期個体に配る値でしかなく、
   * 以降の各個体の速度は遺伝と選択で決まる。整数でなくてもよい。
   */
  speed: number;
  /**
   * 速度を遺伝させる場合の設定。省略すると speed は種の定数として固定される。
   * 実効代謝に speedCost が乗るので、速いことに代償が無いと一方向に上がり続ける。
   */
  mutation?: MutationDef;
  /**
   * 密度に比例した追加の死亡。省略すると何も起きない（既定）。
   * これを入れると個体数が下がるので、上位の捕食者は餌を失う。
   * 14 で踏んだ交絡（叩くと捕食圧が変わる）と同じ形が出るため、
   * 実際に取り除いた数（`World.deathsCrowding`）を必ず確かめること。
   */
  crowding?: CrowdingDef;
  /**
   * 接触で伝わる感染症。省略すると何も起きない（既定）。
   *
   * `transmit` などは**感染する側（未感染の個体）の種定義**から読む。
   * scope が `all` のとき、種ごとに違う値を入れると
   * 「誰から移ったか」で確率が変わらないぶん解釈が楽になる代わりに、
   * 種間の非対称が入る。対照として使うなら全種で同じ値にすること。
   */
  infection?: InfectionDef;
  /**
   * 視界の広さ（セル）。0ならランダムウォーク。
   * 1以上なら周囲を見て、捕食者から逃げる → 獲物を追う → 草の多い方へ、の順で動く。
   * 広げるほど1ステップの計算量が (2r+1)^2 で増えるので効く範囲で小さく。
   */
  visionRange: number;
  /**
   * 空腹とみなすエネルギー。下回ると逃走より採餌を優先する（リスクを取る）。
   *
   * 0 なら常に満腹扱いで、捕食者が見えている限り餌を探さない。視野0の種には
   * 影響しない（そもそも逃走も追跡もしないため）。
   */
  hungerThreshold: number;

  /** 寿命（ステップ）。0なら寿命なし */
  maxAge: number;

  /**
   * 死んだときに自分のいたセルの草へ戻る量。0なら還元なし（既定）。
   *
   * **食べられて死んだ個体は戻さない。** 体が捕食者に移っているため。
   * 戻るのは餓死と寿命死だけで、実装上は捕食で死んだ個体が代謝の手番に
   * 到達しないことで自動的にそうなる。
   *
   * これは草の回復速度とは別口でエネルギーを注ぎ込む操作なので、
   * 放っておくと豊穣化（[06](../../docs/reports/06-enrichment.md)）と区別がつかない。
   * 実際に死骸から入った量は step が別に数えている。
   */
  corpseGrass: number;
  /**
   * 死骸をまき散らす半径（セル）。0なら死んだセルに全部落ちる（既定）。
   * 1以上なら (2r+1)^2 セルへ均等に分ける。
   *
   * 死骸は1セルに固まって落ちるので、草食動物が1回に食べられる量（採食量）を
   * 大きく超えた山になる。時間方向の均し（detritusRelease）と対にして、
   * **空間方向に均したらどうなるか**を見るための軸。
   */
  corpseSpread: number;

  /** 初期個体数 */
  initialCount: number;
  /** 初期エネルギー */
  initialEnergy: number;
}

/**
 * 草地の空間的な不均質さ。回復速度をセルごとに変える。
 *
 * 重みの平均はちょうど1に正規化されるので、`regrow` が表す
 * **世界全体の生産量は変わらない**。分布だけが変わる。
 * 豊穣化（生産量そのものを増やす操作、[06](../../docs/reports/06-enrichment.md)）と
 * 混ざらないようにするため。
 */
export interface GrassPatchConfig {
  /**
   * パッチの大きさ（セル）。世界の幅と高さを割り切る値であること。
   * 小さいほど細かいまだら、大きいほど広い草原と荒野に分かれる。
   */
  scale: number;
  /**
   * 不均質の強さ (0-1)。0なら一様。
   * 回復速度は最も痩せたセルで `regrow × (1-contrast)`、
   * 最も豊かなセルで `regrow × (1+contrast)` になる。1なら痩せた側は完全な不毛地。
   */
  contrast: number;
}

export interface GrassConfig {
  /** セルあたりの草の最大量 */
  max: number;
  /** 1ステップあたりの回復量。パッチがある場合は世界の平均値になる */
  regrow: number;
  /** 初期量（max に対する割合 0-1） */
  initialRatio: number;
  /** 空間的な不均質。省略か contrast=0 なら一様（既定） */
  patch?: GrassPatchConfig;
  /**
   * 死骸をいったんセルごとの在庫（デトリタス）に積み、毎ステップこの割合だけ
   * 草に変える (0-1]。1なら在庫を素通りして即座に草になる＝既定で、
   * [08](../../docs/reports/08-corpse-recycling.md) と同じ挙動。
   *
   * 在庫はローパスフィルタとして働くので、**総入力を変えずに流入のばらつき
   * だけを下げられる**。08で「効いているのは変動係数」まで絞れたので、
   * それを直接動かすための操作。
   */
  detritusRelease?: number;
}

/**
 * 無作為な大量死（噴火・隕石に相当）。一定の間隔で、生きている個体を
 * **形質と無関係に**一定の確率で殺す。
 *
 * 狙いは揺らぎの大きさを動かすつまみ。[13](../../docs/reports/13-escape.md) では
 * 捕食が丘（速度の最適）と揺らぎの両方を作るので分離できず、揺らぎだけが違う世界を
 * 作れなかった。無作為な死は速度の得失に触れないので、丘の位置を動かさずに谷を作れる。
 *
 * ただし**平均死亡率を上げれば平均個体数も下がる**。谷を作ると同時に系を痩せさせる
 * ので、それだけでは 06 の豊穣化を逆向きにやったのと区別がつかない。
 * 比較は `fraction / interval`（1ステップあたりに取り除く割合）を揃えた組の間で行う。
 * 揃えれば動くのは**まとめ方**だけになる——小刻みに削るか、たまに大きく削るか。
 *
 * 実際に取り除いた数は `World.deathsDisturbance` が種別に数えている。
 * 設計上の割合と実現値がずれていないかを毎回確かめること。
 *
 * 省略すると何も起きず、乱数も一切消費しない。
 */
export interface DisturbanceConfig {
  /**
   * 発生の**平均**間隔（ステップ）。0以下なら起きない。
   *
   * 等間隔ではなく、毎ステップ確率 1/interval で起こす（幾何分布）。
   * 等間隔にすると捕食者と被食者の振動と位相が固定されうる。この模型は
   * 周期を持つので、いつも同じ位相で叩けば「大量死の効果」ではなく
   * 「その位相で叩いた効果」を測ることになる（[08](../../docs/reports/08-corpse-recycling.md)
   * で踏んだ周期の罠と同じ形。[12](../../docs/reports/12-invasion.md) が投入の
   * 間隔に jitter を入れたのも同じ理由）。
   */
  interval: number;
  /** 1回の大量死で各個体が死ぬ確率 (0-1)。0なら起きない */
  fraction: number;
  /**
   * 対象にする種の id。省略すると全種。
   *
   * 全種を叩くと「草食が谷に落ちる」と「捕食圧が下がる」が同時に起きる。
   * 13 でこの2つを切り分けるのに苦労したので、片方だけ叩ける形にしてある。
   */
  species?: number[];
}

export interface WorldConfig {
  width: number;
  height: number;
  seed: number;
  grass: GrassConfig;
  species: SpeciesDef[];
  /** エージェント数の上限。超える分は繁殖が抑制される */
  maxAgents: number;
  /** 無作為な大量死。省略すると何も起きない（既定） */
  disturbance?: DisturbanceConfig;
}

/** 1ステップ分の統計 */
export interface StepStats {
  step: number;
  /** species id -> 個体数 */
  population: Map<number, number>;
  /** 草の総量 */
  totalGrass: number;
}
