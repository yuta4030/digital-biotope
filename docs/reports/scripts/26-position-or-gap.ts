import { presetByKey } from '../../../src/core/presets.ts';
import { trial, header, done, banner } from './_lib.ts';
import type { WorldConfig } from '../../../src/core/types.ts';

/**
 * レポート26: 共存の窓を決めているのは絶対位置か、2種の間隔か
 *
 *   node docs/reports/scripts/26-position-or-gap.ts
 *
 * [25](../25-low-hill-check.md) 節3 は警戒型を視野3に固定して無警戒型だけを振った。
 * その結果、**「低いほうの絶対位置」と「2種の間隔」が同時に動いていた**。
 *
 *   低 0.00 → 絶対位置 0.00 / 間隔 3.00   警戒型 481体
 *   低 0.50 → 絶対位置 0.50 / 間隔 2.50   警戒型  78体
 *   低 0.80 → 絶対位置 0.80 / 間隔 2.20   警戒型   0体
 *
 * 境界を説明する規則が2つあり、25 のデータはどちらとも整合する。
 *
 *   規則A（絶対位置）  低いほうが c より下なら共存。c は 0.5〜0.8 のどこか
 *   規則G（間隔）      間隔が d より広ければ共存。d は 2.2〜2.5 のどこか
 *
 * **分けるには低いほうを0に固定して、高いほうを下げる。**
 * 低いほうの絶対位置が0で動かないので、動くのは間隔だけになる。
 * 予測が分かれる点は 低0 / 高1.5（Aは共存、Gは崩壊）。
 *
 * ## 予測を先に書く
 *
 * **規則A が当たると読んでいる。** 根拠は 22 節5 の採食統計で、
 * 視野1・2・3 は採食の仕方がほとんど同じだった（15.4%/2.761、16.4%/2.756、
 * 17.2%/2.769）。**崖は 0 と 1 の間にしかない。** だとすると視野1の個体と
 * 視野3の個体は「同じ規則の、値段違い」でしかなく、規則としては1つ。
 * 2本目の軸を作っているのは「見るか見ないか」であって「どれだけ遠くを見るか」ではない。
 *
 * そうなら間隔は本質ではなく、効くのは**低いほうがどれだけ盲目でいるか**になる。
 *
 * **ただし別の壊れ方がありうる。** 高いほうを下げると実効代謝が下がる
 * （視野3で0.475、視野1で0.425）ので、高いほうが**強くなりすぎて低いほうを
 * 排除する**かもしれない。21 が「同じ規則の中では R* の低いほうが勝つ」と
 * 出しているので、規則が1つに畳まれるならこれが起きる。
 * **どちらが消えたかを必ず見ること。** 崩壊の向きで話が変わる。
 *
 * 4スレッドで約35分。
 */

const t0 = performance.now();
banner();
const SEEDS_8 = [1000, 2000, 3000, 4000, 5000, 6000, 7000, 8000];

/**
 * 21 の共存構成（`upkeep` から捕食者を消したもの）で、草食2種の視野を両方指定する。
 * 2種の違いは視野だけなので、これで軸の上の2点を自由に置ける。
 *
 * 端数を使うには `visionMutation` が要る（無いと定義値がそのまま走査半径に入り、
 * 非整数だと添字が壊れる）。σ=0 で値は動かないが子1体につき正規乱数を1つ引く。
 * **両種で同じ**なので比較は公平。25 節3 と同じ扱いにしてある。
 */
function pairAt(vLo: number, vHi: number, invader = 0): () => WorldConfig {
  return () => {
    const cfg = presetByKey('upkeep').build();
    cfg.species[2].initialCount = 0; // 21 の共存は捕食者なしで測られている
    for (const herb of [cfg.species[0], cfg.species[1]]) {
      herb.visionMutation = { sigma: 0, min: 0, max: 5 };
    }
    cfg.species[0].visionRange = vHi; // id 1
    cfg.species[1].visionRange = vLo; // id 2
    if (invader > 0) {
      for (const s of cfg.species) {
        if (s.id === 3) continue;
        s.initialCount = s.id === invader ? 5 : 300;
      }
    }
    return cfg;
  };
}

/**
 * 1行出す。**どちらが消えたかが読めることが肝。**
 * 「共存が壊れた」だけでは、間隔が足りなかったのか高いほうが強くなりすぎたのかが
 * 分からない（このレポートの見立ての分岐点）。
 */
async function row(vLo: number, vHi: number, steps: number, invader = 0): Promise<void> {
  const t = await trial(pairAt(vLo, vHi, invader), { seeds: SEEDS_8, steps, tail: steps / 6 });
  const [hi, lo] = t.species;
  const total = hi.mean + lo.mean;
  const share = total > 0 ? (hi.mean / total) * 100 : NaN;
  const who =
    hi.mean === 0 ? ' 高い側が消えた' : lo.mean === 0 ? ' 低い側が消えた' : '';
  const tag = invader > 0 ? `  ${invader === 1 ? '高' : '低'}が5体から` : '';
  console.log(
    `  低 ${vLo.toFixed(2)} / 高 ${vHi.toFixed(2)}  間隔 ${(vHi - vLo).toFixed(2)}${tag.padEnd(14)}` +
      `  高い側 ${hi.mean.toFixed(0).padStart(4)}(${String(hi.min).padStart(3)}-${String(hi.max).padStart(4)})` +
      `  低い側 ${lo.mean.toFixed(0).padStart(4)}(${String(lo.min).padStart(3)}-${String(lo.max).padStart(4)})` +
      `  高 ${share.toFixed(0).padStart(3)}%${who}`,
  );
}

// ---------------------------------------------------------------------------
// 節1: 低いほうを0に固定して、高いほうを下げる。**これが分離の本体。**
//
// 低いほうの絶対位置が0で動かないので、動くのは間隔だけ。
//   規則A（絶対位置）が正しい → 高1.0 まで下げても共存が残る
//   規則G（間隔）が正しい     → 間隔2.2〜2.5 のあたりで壊れる（高2.2〜2.5）
//
// 規則7 に従って最初から30000歩で測る。25 節4 の σ=0.01 が
// 「6000歩では共存に見えて30000歩で1体」だったので、6000歩の screening は信用しない。
// ---------------------------------------------------------------------------
header('低い側を0に固定して高い側を下げる（8シード・30000歩・変異なし）');
for (const vHi of [3.0, 2.5, 2.0, 1.5, 1.0]) {
  await row(0, vHi, 30000);
}

// ---------------------------------------------------------------------------
// 節2: 25 が残した窓の端を詰める。高いほうは3のまま。
//
// 25 は 0.50 で警戒型78体、0.80 で0体まで出して、間を測っていない。
// 端が 0.55 なのか 0.78 なのかで、進化の着地点（0.81）までの距離が変わる。
//
// **この帯の高い側は個体数が小さくなる**（0.50 で78体）。規則2 のとおり
// 平均ではなく最小を見ること。境界付近は偶然で消えうる。
// ---------------------------------------------------------------------------
header('窓の端を詰める（高い側は3・8シード・30000歩）');
for (const vLo of [0.55, 0.6, 0.65, 0.7, 0.75]) {
  await row(vLo, 3.0, 30000);
}

// ---------------------------------------------------------------------------
// 節3: 2つの規則の予測が分かれる点を直接踏む。
//
// 低0.25/高1.5 は 規則A なら共存（低が0.25）、規則G なら崩壊（間隔1.25）。
// 低0.50/高1.5 も同じく分かれる（間隔1.00）。
// 節1 が高い側だけを動かした線なので、こちらは斜めに入って2次元で確かめる。
// ---------------------------------------------------------------------------
header('予測が分かれる点（8シード・30000歩）');
await row(0.25, 1.5, 30000);
await row(0.5, 1.5, 30000);
await row(0.25, 1.0, 30000);

// ---------------------------------------------------------------------------
// 節4: 生き残った組を相互侵入にかける。
//
// 25 で「30000歩でも動かないのに実は遅い排除」（σ=0.01）を踏んでいるので、
// 個体数が安定しているだけでは共存と呼ばない。21 節5 と同じ判定を当てる。
//
// 低0/高1.0 は 規則A と 規則G で予測が最も割れる点なので、
// ここが両方向で通るかどうかがこのレポートの結論を決める。
// ---------------------------------------------------------------------------
header('相互侵入（8シード・30000歩・片方を5体から）');
for (const [vLo, vHi] of [
  [0, 1.0],
  [0, 2.0],
  [0.65, 3.0],
] as const) {
  for (const invader of [1, 2]) {
    await row(vLo, vHi, 30000, invader);
  }
}

await done(t0);
